const FOLD = { 'É': 'E', 'È': 'E', 'Ê': 'E', 'Ë': 'E', 'À': 'A', 'Â': 'A', 'Î': 'I', 'Ï': 'I', 'Ô': 'O', 'Ù': 'U', 'Û': 'U', 'Ç': 'C' };

export function textWidth(s) { return s.length * 4 - 1; }

/** Draw `s` with its top-left at (x, y) in the current pixel space; optional 1px dark outline. */
export function drawText(ctx, s, x, y, color = '#fff', outline = '#000') {
  const up = s.toUpperCase();
  x = Math.round(x); y = Math.round(y);
  const pass = (col, ox, oy) => {
    ctx.fillStyle = col;
    for (let i = 0; i < up.length; i++) {
      const ch = FOLD[up[i]] || up[i];
      const g = G[ch];
      if (!g) continue;
      for (let j = 0; j < 15; j++) if (g[j] === '1') ctx.fillRect(x + i * 4 + (j % 3) + ox, y + ((j / 3) | 0) + oy, 1, 1);
    }
  };
  if (outline) for (const [ox, oy] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) pass(outline, ox, oy);
  pass(color, 0, 0);
}
